/** “所需权限值”类权限的前缀：i_needed_modify_power_<基础权限名去掉 b_/i_ 前缀> */
const NEEDED_POWER_PREFIX = 'i_needed_modify_power_';

/**
 * 取得权限的中文显示名。找不到时返回 undefined，调用方应回退显示原始 permsid。
 * permsid 本身永远原样保留，不参与任何翻译或比较。
 */
export function getPermissionLabel(permsid: string): string | undefined {
  const direct = PERMISSION_LABELS[permsid];
  if (direct) return direct;

  // “所需权限值”在服务端没有描述，与基础权限一一对应，直接复用其译文并加前缀说明
  if (permsid.startsWith(NEEDED_POWER_PREFIX)) {
    const rest = permsid.slice(NEEDED_POWER_PREFIX.length);
    const base = PERMISSION_LABELS[`b_${rest}`] ?? PERMISSION_LABELS[`i_${rest}`];
    return base ? `所需权限值：${base}` : undefined;
  }

  return undefined;
}
